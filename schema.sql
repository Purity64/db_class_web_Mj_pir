CREATE TABLE users (
    user_id INT AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) DEFAULT 'customer',
    user_token VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_id PRIMARY KEY (user_id),
    CONSTRAINT unk_user_token UNIQUE (user_token),
    CONSTRAINT ck_role CHECK (role IN ('employee', 'customer'))
);

CREATE TABLE `role`(
    role_id INT AUTO_INCREMENT,
    name VARCHAR(20) NOT NULL,

    CONSTRAINT pk_role_id PRIMARY KEY (role_id)
);

CREATE TABLE role_line(
    role_line_id INT AUTO_INCREMENT,
    role_id INT NOT NULL,

    CONSTRAINT pk_role_line_id PRIMARY KEY (role_line_id),
    CONSTRAINT fk_role_id FOREIGN KEY (role_id) REFERENCES `role`(role_id) ON DELETE CASCADE
);

CREATE TABLE user_employee (
    employee_id INT NOT NULL,
    role_line_id INT NOT NULL,

    CONSTRAINT pk_employee_id PRIMARY KEY (employee_id),
    CONSTRAINT fk_employee_id FOREIGN KEY (employee_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_role_line_id FOREIGN KEY (role_line_id) REFERENCES role_line(role_line_id) ON DELETE CASCADE
);

CREATE TABLE user_customer (
    customer_id INT NOT NULL,
    referrals INT NULL,
    money DECIMAL(12,2) DEFAULT 0.00,
    tier VARCHAR(20) DEFAULT 'normal',

    CONSTRAINT pk_customer_id PRIMARY KEY (customer_id),
    CONSTRAINT fk_customer_id FOREIGN KEY (customer_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_money CHECK (money >= 0),
    CONSTRAINT fk_user_referrals FOREIGN KEY (referrals) REFERENCES user_customer(customer_id) ON DELETE SET NULL,
    CONSTRAINT ck_tier CHECK (tier IN ('normal', 'vip'))
);

CREATE TABLE address (
    address_id INT AUTO_INCREMENT,
    user_id INT NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(100) NOT NULL,
    house_address VARCHAR(100) NOT NULL,
    moo VARCHAR(100) NOT NULL,
    soi VARCHAR(100) NOT NULL,
    road VARCHAR(100) NOT NULL,
    sub_district VARCHAR(100) NOT NULL,
    district VARCHAR(100) NOT NULL,
    province VARCHAR(100) NOT NULL,
    postal_code INT NOT NULL,
    note VARCHAR(255) NULL,
    address_token VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_address_id PRIMARY KEY (address_id),
    CONSTRAINT fk_address_user_id FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT unk_address_token UNIQUE (address_token)
);

CREATE TABLE category (
    category_id INT AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL,
    category_token VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_category_id PRIMARY KEY (category_id),
    CONSTRAINT unk_category_token UNIQUE (category_token)
);

CREATE TABLE product (
    product_id INT AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    detail VARCHAR(255) NOT NULL,
    price DECIMAL(10,2) DEFAULT 0.00,
    total INT DEFAULT 0,
    isOpen BOOLEAN DEFAULT FALSE,
    product_token VARCHAR(255) NOT NULL,
    employee_id INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_product_id PRIMARY KEY (product_id),
    CONSTRAINT unk_product_token UNIQUE (product_token),
    CONSTRAINT ck_price CHECK (price >= 0),
    CONSTRAINT fk_employee FOREIGN KEY (employee_id) REFERENCES user_employee(employee_id) ON DELETE RESTRICT
);

-- ตาราง Junction Table เชื่อม M:N ระหว่าง Category กับ Product
CREATE TABLE category_line (
    category_line_id INT AUTO_INCREMENT,
    category_token VARCHAR(255) NOT NULL,
    product_token VARCHAR(255) NOT NULL,

    CONSTRAINT pk_category_line_id PRIMARY KEY (category_line_id),
    CONSTRAINT fk_category_token FOREIGN KEY (category_token) REFERENCES category(category_token) ON DELETE CASCADE,
    CONSTRAINT fk_product_token FOREIGN KEY (product_token) REFERENCES product(product_token) ON DELETE CASCADE
);

CREATE TABLE review (
    review_id INT AUTO_INCREMENT,
    user_id INT NOT NULL,
    product_id INT NOT NULL,
    rating INT NOT NULL,
    comment VARCHAR(255) NULL,
    review_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_review_id PRIMARY KEY (review_id),
    CONSTRAINT fk_review_user_id FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_product_id FOREIGN KEY (product_id) REFERENCES product(product_id) ON DELETE CASCADE,
    CONSTRAINT unique_customer_product_review UNIQUE (user_id, product_id),
    CONSTRAINT ck_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE shop_order (
    order_id INT AUTO_INCREMENT,
    customer_id INT NOT NULL,
    employee_id INT NULL,
    order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_amount DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(50) NOT NULL DEFAULT 'pending',
    address_token VARCHAR(255) NOT NULL,

    CONSTRAINT pk_order_id PRIMARY KEY (order_id),
    CONSTRAINT fk_order_customer_id FOREIGN KEY (customer_id) REFERENCES user_customer(customer_id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_employee_id FOREIGN KEY (employee_id) REFERENCES user_employee(employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_address_token FOREIGN KEY (address_token) REFERENCES address(address_token) ON DELETE RESTRICT,
    CONSTRAINT ck_total_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_status CHECK (status IN ('pending', 'waiting_paid', 'paid', 'delivered', 'cancelled', 'succeed', 'shipped'))
);

CREATE TABLE order_line (
    order_line_id INT AUTO_INCREMENT,
    order_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity INT NOT NULL,
    unit_price DECIMAL(10, 2) NOT NULL,

    CONSTRAINT pk_order_line_id PRIMARY KEY (order_line_id),
    CONSTRAINT fk_order_line_order_id FOREIGN KEY (order_id) REFERENCES shop_order(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_line_product_id FOREIGN KEY (product_id) REFERENCES product(product_id) ON DELETE RESTRICT,
    CONSTRAINT ck_quantity CHECK (quantity > 0),
    CONSTRAINT ck_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE payment (
    payment_id INT AUTO_INCREMENT,
    order_id INT NULL,
    method VARCHAR(10) NOT NULL,
    amount DECIMAL(10, 2) NOT NULL,
    paid_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payment_id PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_order_id FOREIGN KEY (order_id) REFERENCES shop_order(order_id) ON DELETE CASCADE,
    CONSTRAINT ck_method CHECK (method IN ('cash', 'bank', 'point')),
    CONSTRAINT ck_pay_amount CHECK (amount >= 0)
);

